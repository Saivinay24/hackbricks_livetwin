def build_full_text(incident: dict) -> str:
    """Concatenate all incident fields into a single string for embedding."""
    return (
        f"Incident {incident['incident_id']} | "
        f"Asset type: {incident['asset_type']} | "
        f"Failure mode: {incident['failure_mode']} | "
        f"Sensor pattern: {incident['sensor_pattern']} | "
        f"Severity: {incident['severity']} | "
        f"Operating condition: {incident['operating_condition']} | "
        f"Root cause: {incident['root_cause']} | "
        f"Corrective action: {incident['corrective_action']} | "
        f"Outcome: {incident['outcome']} | "
        f"Cost: {incident['cost']} INR | "
        f"Downtime: {incident['downtime_hours']} hours | "
        f"Technician notes: {incident['technician_notes']} | "
        f"Tags: {', '.join(incident['tags'])}"
    )

for inc in INCIDENTS:
    inc["full_text"] = build_full_text(inc)

